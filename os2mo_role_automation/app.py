from fastapi import FastAPI
from fastramqpi.events import GraphQLEvents
from fastramqpi.events import Listener
from fastramqpi.events import Namespace
from fastramqpi.main import FastRAMQPI

from os2mo_role_automation import depends
from os2mo_role_automation import events
from os2mo_role_automation.autogenerated_graphql_client import GraphQLClient
from os2mo_role_automation.config import Settings
from os2mo_role_automation.constants import EVENT_NAMESPACE


def create_app() -> FastAPI:
    settings = Settings()

    fastramqpi = FastRAMQPI(
        application_name="role_automation",
        settings=settings.fastramqpi,
        graphql_version=30,
        graphql_client_cls=GraphQLClient,
        graphql_events=GraphQLEvents(
            declare_namespaces=[Namespace(name=EVENT_NAMESPACE)],
            declare_listeners=[
                # Internal listeners
                # ------------------
                # We normalize all changes to this internal ituser queue.
                Listener(
                    namespace=EVENT_NAMESPACE,
                    user_key="role-automation-ituser",
                    routing_key="ituser",
                    path="/events/ituser",
                ),
                Listener(
                    namespace=EVENT_NAMESPACE,
                    user_key="role-automation-engagement",
                    routing_key="engagement",
                    path="/events/engagement",
                ),
                # MO listeners
                # ------------
                Listener(
                    namespace="mo",
                    user_key="role-automation-mo-engagement",
                    routing_key="engagement",
                    path="/events/mo/engagement",
                ),
                Listener(
                    namespace="mo",
                    user_key="role-automation-mo-org-unit",
                    routing_key="org_unit",
                    path="/events/mo/org_unit",
                ),
            ],
        ),
    )
    fastramqpi.add_context(settings=settings)

    # FastAPI router
    app = fastramqpi.get_app()
    app.include_router(events.router)

    @app.get("/test")
    async def test(graphql_client: depends.GraphQLClient) -> str:
        root = await graphql_client.get_root()
        return root.user_key

    return app
