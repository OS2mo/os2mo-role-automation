from datetime import datetime
from datetime import time
from uuid import UUID
from uuid import uuid5
from zoneinfo import ZoneInfo

# todo add to poetry
import structlog

from os2mo_role_automation.autogenerated_graphql_client import GraphQLClient
from os2mo_role_automation.autogenerated_graphql_client import RAValidityInput
from os2mo_role_automation.autogenerated_graphql_client import RoleBindingCreateInput
from os2mo_role_automation.autogenerated_graphql_client import RoleBindingTerminateInput

logger = structlog.stdlib.get_logger()
TIMEZONE = ZoneInfo("Europe/Copenhagen")
ROLEBINDING_USER_KEY = "managed-by-role-automation"


def rolebinding_uuid(ituser: UUID, role: UUID) -> UUID:
    """The UUID of the engine's rolebinding of the role to the IT user."""
    ns = UUID("19e09b81-9b5b-4c13-b1f8-91233ccd6f89")
    return uuid5(ns, f"{ituser}:{role}")


async def get_actual_state(
    graphql_client: GraphQLClient,
    ituser: UUID,
) -> set[UUID]:
    """Return all roles currently bound for ituser."""
    actual_state = set()

    response = await graphql_client.get_actual_state(ituser, ROLEBINDING_USER_KEY)
    for obj in response.objects:
        if obj.current is None:
            continue
        actual_state.add(obj.current.role_response.uuid)

    return actual_state


async def get_desired_state(
    graphql_client: GraphQLClient,
    ituser: UUID,
) -> set[UUID]:
    # This is the last function to be implmented. Right now, the engine simply
    # believes nothing should exist :)
    return set()


def plan(
    actual_state: set[UUID], desired_state: set[UUID]
) -> tuple[set[UUID], set[UUID]]:
    to_create = desired_state - actual_state
    to_remove = actual_state - desired_state
    return to_create, to_remove


async def reconcile(
    graphql_client: GraphQLClient,
    ituser: UUID,
):
    today = datetime.now(TIMEZONE).date()
    midnight = datetime.combine(today, time(), tzinfo=TIMEZONE)
    log = logger.bind(ituser=ituser)

    actual_state = await get_actual_state(graphql_client, ituser)
    desired_state = await get_desired_state(graphql_client, ituser)

    to_create, to_remove = plan(actual_state, desired_state)

    for role in to_create:
        uuid = rolebinding_uuid(ituser, role)
        log.info("Creating rolebinding", uuid=uuid, role=role)
        await graphql_client.create_rolebinding(
            RoleBindingCreateInput(
                uuid=uuid,
                user_key=ROLEBINDING_USER_KEY,
                ituser=ituser,
                role=role,
                validity=RAValidityInput(from_=midnight),
            )
        )

    for role in to_remove:
        uuid = rolebinding_uuid(ituser, role)
        log.info("Removing rolebinding", uuid=uuid, role=role)
        await graphql_client.terminate_rolebinding(
            RoleBindingTerminateInput(uuid=uuid, to=midnight)
        )
