from uuid import UUID

from fastapi import APIRouter
from fastramqpi.events import Event

from os2mo_role_automation import depends
from os2mo_role_automation.autogenerated_graphql_client import EventSendInput
from os2mo_role_automation.autogenerated_graphql_client import GraphQLClient
from os2mo_role_automation.constants import EVENT_NAMESPACE

router = APIRouter()


async def send_event(
    graphql_client: GraphQLClient, routing_key: str, subject: UUID, priority: int
) -> None:
    await graphql_client.send_event(
        EventSendInput(
            namespace=EVENT_NAMESPACE,
            routing_key=routing_key,
            subject=str(subject),
            priority=priority,
        )
    )


@router.post("/events/mo/engagement")
async def mo_engagement(
    event: Event[UUID], graphql_client: depends.GraphQLClient
) -> None:
    # Pass to internal engagement listener.
    await send_event(graphql_client, "engagement", event.subject, event.priority)


@router.post("/events/engagement")
async def engagement(event: Event[UUID], graphql_client: depends.GraphQLClient) -> None:
    # We reconcile any IT user that has ever been connected to this engagement.
    cursor = None
    while True:
        response = await graphql_client.get_engagement_i_t_users(
            cursor=cursor, engagement=event.subject
        )
        for ituser in response.objects:
            await send_event(
                graphql_client,
                "ituser",
                ituser.uuid,
                event.priority,
            )
        cursor = response.page_info.next_cursor
        if cursor is None:
            break


@router.post("/events/ituser")
async def ituser(event: Event[UUID]) -> None:
    print("reconciling", event.subject)
